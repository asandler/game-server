void make_ray(field& f, int i, int j, int dx, int dy, char c)
{
    if (ray(f, i, j, dx, dy, c))
    {
        i += dx;
        j += dy;
        while (i > -1 && i < 8 && j > -1 && j < 8 && f[i][j] == revert_turn(c))
        {
            f[i][j] = c;
            i += dx;
            j += dy;
        }
    }
}

bool ray(const field& f, int i, int j, int dx, int dy, char c)
{
    i += dx;
    j += dy;
    bool b = false;
    while (i > -1 && i < 8 && j > -1 && j < 8 && f[i][j] == revert_turn(c))
    {
        i += dx;
        j += dy;
        b = true;
    }
    return i > -1 && i < 8 && j > -1 && j < 8 && b && f[i][j] == c;
}

struct score_t
{
    int sc;
    int ang;
    score_t() {}
    score_t(int _ang, int _sc)
    {
        sc = _sc;
        ang = _ang;
    }
    bool operator<(const score_t& other) const
    {
        if (ang != other.ang)
            return ang < other.ang;
        return sc < other.sc;
    }
    bool operator>(const score_t& other) const
    {
        if (ang != other.ang)
            return ang > other.ang;
        return sc > other.sc;
    }
    score_t operator-() const
    {
        return score_t(-ang, -sc);
    }
};

