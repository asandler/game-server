bool can_do(const field& f, int i, int j)
{
    if (f[i][j] != '.')
        return false;
    return ray(f, i, j, 0, 1, f.turn) ||
           ray(f, i, j, 0, -1, f.turn) ||
           ray(f, i, j, 1, 0, f.turn) ||
           ray(f, i, j, -1, 0, f.turn) ||
           ray(f, i, j, 1, 1, f.turn) ||
           ray(f, i, j, 1, -1, f.turn) ||
           ray(f, i, j, -1, 1, f.turn) ||
           ray(f, i, j, -1, -1, f.turn);
}

bool finish(const field& _f)
{
    field f = _f;
    for (int i = 0; i < 8; i++)
        for (int j = 0; j < 8; j++)
            if (can_do(f, i, j))
                return false;
    f.turn = revert_turn(f.turn);
    for (int i = 0; i < 8; i++)
        for (int j = 0; j < 8; j++)
            if (can_do(f, i, j))
                return false;
    return true;
}

