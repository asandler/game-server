struct field
{
    array<string, 8> pos;
    char turn;
    field()
    {
        turn = '#';
        for (int i = 0; i < 8; i++)
            pos[i] = "........";
        pos[3][3] = 'O';
        pos[4][4] = 'O';
        pos[3][4] = '#';
        pos[4][3] = '#';
    }
    void make_turn(int i, int j)
    {
        if (i > -1)
        {
            pos[i][j] = turn;
            make_ray(*this, i, j, 0, 1, turn);
            make_ray(*this, i, j, 1, 0, turn);
            make_ray(*this, i, j, 0, -1, turn);
            make_ray(*this, i, j, -1, 0, turn);
            make_ray(*this, i, j, 1, 1, turn);
            make_ray(*this, i, j, 1, -1, turn);
            make_ray(*this, i, j, -1, 1, turn);
            make_ray(*this, i, j, -1, -1, turn);
        }
        turn = revert_turn(turn);
    }
    string& operator[](const int& i)
    {
        return pos[i];
    }
    const string& operator[](const int& i) const
    {
        return pos[i];
    }
};

