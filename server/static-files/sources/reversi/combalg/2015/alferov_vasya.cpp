struct perceptron
{
    array<double, HIDDEN_LAYER_SIZE> hidden_layer_threshold; 
    array<array<double, HIDDEN_LAYER_SIZE>, 64> input_to_hidden_weights;
    array<double, HIDDEN_LAYER_SIZE> hidden_to_output_weights;
    //This generates perceptron with thresholds and weights - random numbers from Gaussian distribution
    perceptron() {}
    double get_score(const field& f);
};

