double activating_func(double x)
{
    return (exp(2 * x) - 1) / (exp(2 * x) + 1);
}

double get_val(char c)
{
    if (c == 'O')
        return -1;
    else if (c == 'X')
        return 1;
    else
        return 0;
}

double perceptron::get_score(const field& f)
{
    array<double, 64> input_layer_values;
    for (int i = 0; i < 8; i++)
        for (int j = 0; j < 8; j++)
            input_layer_values[8 * i + j] = get_val(f[i][j]);
    array<double, HIDDEN_LAYER_SIZE> hidden_layer_input;
    for (int i = 0; i < HIDDEN_LAYER_SIZE; i++)
        hidden_layer_input[i] = 0;
    for (int i = 0; i < 64; i++)
        for (int j = 0; j < HIDDEN_LAYER_SIZE; j++)
            hidden_layer_input[j] += input_to_hidden_weights[i][j] * input_layer_values[i];
    array<double, HIDDEN_LAYER_SIZE> hidden_layer_output;
    for (int i = 0; i < HIDDEN_LAYER_SIZE; i++)
        hidden_layer_output[i] = activating_func(hidden_layer_threshold[i] * hidden_layer_input[i]);
    double ans = 0;
    for (int i = 0; i < HIDDEN_LAYER_SIZE; i++)
        ans += hidden_layer_output[i] * hidden_to_output_weights[i];
    return ans;
}

