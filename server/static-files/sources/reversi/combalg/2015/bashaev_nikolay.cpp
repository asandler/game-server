double getRandNum(double lb, double rb)
{
    return lb + ((double)rand() * ((rb - lb) / (double)RAND_MAX));
}

int getBit(unsigned long long mask, int pos)
{
    return ((mask & ((unsigned long long)1 << pos)) >> pos);
}

unsigned long long setBit(unsigned long long mask, int pos, int val)
{
    unsigned long long res = mask & (~((unsigned long long)1 << pos));
    res |= ((unsigned long long)val << pos);

    return res;
}

struct Mask
{
    unsigned long long bMask, wMask;

    Mask(unsigned long long b = 0, unsigned long long w = 0)
    {
        bMask = b;
        wMask = w;
    }

    Mask setEl(int pos, int type)
    {
        int val = (type + 1) / 2;
        return Mask(setBit(bMask, pos, val), setBit(wMask, pos, 1 - val));
    }

    int getType(int pos)
    {
        return getBit(bMask, pos) - getBit(wMask, pos);
    }

    void print()
    {
        for (int i = 0; i < fSize; i++)
        {
            if (i % 8 == 0) cout << "\n";
            cout << ((this->getType(i) == -1) ? 'w' : ((this->getType(i) == 0) ? '0' : 'b'));
        }

        cout << "\n\n";
    }
};

double sigm(double arg)
{
    return 1 / (1 + exp(-arg));
}

struct Network
{
    double weights1[fSize + 1][layerSize];
    double weights2[layerSize + 1];

    Network() {}

    void randInit()
    {
        for (int i = 0; i < fSize + 1; i++)
        {
            for (int j = 0; j < layerSize; j++)
            {
                weights1[i][j] = getRandNum(minBound, maxBound);
            }
        }

        for (int i = 0; i < layerSize + 1; i++)
        {
            weights2[i] = getRandNum(minBound, maxBound);
        }
    }

    void initByParent(Network w)
    {
        for (int i = 0; i < fSize + 1; i++)
        {
            for (int j = 0; j < layerSize; j++)
            {
                weights1[i][j] = w.weights1[i][j] + getRandNum(-maxDelta, maxDelta);
            }
        }

        for (int i = 0; i < layerSize + 1; i++)
        {
            weights2[i] = w.weights2[i] + getRandNum(-maxDelta, maxDelta);
        }
    }

    double getVal(Mask m)
    {
        double v1[layerSize];
        double res = 0;

        for (int i = 0; i < layerSize; i++)
        {
            v1[i] = 0;

            for (int j = 0; j < fSize; j++)
            {
                v1[i] += weights1[j][i] * (double)m.getType(j);
            }

            v1[i] += weights1[fSize][i];
            v1[i] = sigm(v1[i]);
        }

        for (int i = 0; i < layerSize; i++)
        {
            res += weights2[i] * v1[i];
        }

        res += weights2[layerSize];
        res = sigm(res);

        return res;
    }
};


vector<int> getNeighbours(Mask m, int pos, int type)
{
    vector<int> neighb;
    int currPos;
    int nx, ny;

    for (int dx = -1; dx <= 1; dx++)
    {
        for (int dy = -1; dy <= 1; dy++)
        {
            if (dx == 0 && dy == 0) continue;
            currPos = pos;

            while (true)
            {
                nx = (currPos % 8) + dx;
                ny = (currPos / 8) + dy;

                if (nx < 0 || nx >= 8) break;
                if (ny < 0 || ny >= 8) break;

                currPos = ny * 8 + nx;

                if (m.getType(currPos) == 0) break;
                if (m.getType(currPos) == type)
                {
                    if ((currPos - dx - dy * 8) != pos)
                    {
                        neighb.push_back(currPos);
                    }

                    break;
                }
            }
        }
    }

    return neighb;
}

Mask setCell(Mask m, int pos, int type)
{
    Mask res = m;
    vector<int> neighb = getNeighbours(m, pos, type);
    int cPos, fPos;
    int dx, dy;

    for (int i = 0; i < (int)neighb.size(); i++)
    {
        cPos = pos;
        fPos = neighb[i];

        dx = (fPos % 8) - (pos % 8);
        dy = (fPos / 8) - (pos / 8);

        dx /= ((abs(dx) != 0) ? abs(dx) : 1);
        dy /= ((abs(dy) != 0) ? abs(dy) : 1);

        while (cPos != fPos)
        {
            res = res.setEl(cPos, type);
            cPos += dx + dy * 8;
        }
    }

    return res;
}

vector<int> getFreeCells(Mask m, int type)
{
    vector<int> res;

    for (int pos = 0; pos < fSize; pos++)
    {
        if (m.getType(pos) != 0) continue;
        if (getNeighbours(m, pos, type).size() > 0) res.push_back(pos);
    }

    return res;
}

int getResult(Mask m)
{
    int bCount = 0;
    int wCount = 0;

    for (int i = 0; i < fSize; i++)
    {
        bCount += getBit(m.bMask, i);
        wCount += getBit(m.wMask, i);
    }

    return ((bCount > wCount) ? 1 : ((bCount == wCount) ? 0 : -1));
}

int getRandomSolution(Mask m, vector<int> freeCells, int type)
{
    int countOfCells = freeCells.size();
    return freeCells[rand() % countOfCells];
}

int getBestSolution(Network w, Mask m, vector<int> freeCells, int type)
{
    int countOfCells = freeCells.size();
    double prob[countOfCells];
    double val;

    for (int i = 0; i < (int)freeCells.size(); i++)
    {
        val = w.getVal(setCell(m, freeCells[i], type));
        if (type == -1) val = 1 - val;

        prob[i] = i > 0 ? prob[i - 1] : 0;
        prob[i] += val;
    }

    int index = lower_bound(prob, prob + countOfCells, getRandNum(0, prob[countOfCells - 1])) - prob;
    return freeCells[index];
}



